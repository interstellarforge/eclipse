#!/usr/bin/env python3
"""Generates android/.../core/Catalog.kt from the Swift sources, so both apps share the same transitions, effects, overlays, titles and looks."""
import re, sys
src = open('Sources/MovieCore/Model.swift').read()

def enum_block(name):
    i = src.index(f'public enum {name}')
    depth = 0; j = src.index('{', i)
    k = j
    while True:
        if src[k] == '{': depth += 1
        elif src[k] == '}':
            depth -= 1
            if depth == 0: return src[i:k + 1]
        k += 1

def cases(block):
    names = []
    for line in block.split('\n'):
        m = re.match(r'\s+case ([a-zA-Z0-9_, ]+?)(?: = "[^"]*")?\s*$', line) or re.match(r'\s+case ([a-zA-Z0-9_, ]+?)\s*$', line)
        if m and 'return' not in line and ':' not in line:
            names += [n.strip() for n in m.group(1).split(',')]
    return names

def raw_cases(block):
    # for enums with explicit raw strings, e.g. case center = "Center title", lowerThird = "Lower third"
    out = []
    for line in block.split('\n'):
        if re.match(r'\s+case ', line) and '=' in line and 'return' not in line and ':' not in line:
            for m in re.finditer(r'([a-zA-Z0-9]+) = "([^"]*)"', line): out.append((m.group(1), m.group(2)))
    return out

def mapping(block, var):
    m = re.search(r'public var ' + var + r': String \{(.*?)\n    \}', block, re.S)
    if not m: return {}
    return {a: b for a, b in re.findall(r'case \.(\w+): return "((?:[^"\\]|\\.)*)"', m.group(1))}

INTS = {'align', 'animationMs'}
def num(k, v):
    return v + '.0' if re.fullmatch(r'-?[0-9]+', v) and k not in INTS else v

def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'

out = ['// GENERATED by scripts/gen-android-catalog.py from the Swift sources. Do not edit by hand.', 'package app.lumacut.core', '']

# TextAnimation
blk = enum_block('TextAnimation'); t = mapping(blk, 'title')
out.append('enum class TextAnimation(val title: String) {')
out.append(',\n'.join(f'    {c}({q(t[c])})' for c in cases(blk)) + ';\n}\n')

# EffectType
blk = enum_block('EffectType'); t = mapping(blk, 'title'); s = mapping(blk, 'summary')
amount = {}
dm = re.search(r'defaultAmount: Double \{(.*?)\n    \}', blk, re.S).group(1)
for line in dm.split('\n'):
    m = re.match(r'\s+case (.*?): return ([0-9.]+)', line)
    if m:
        for n in re.findall(r'\.(\w+)', m.group(1)): amount[n] = m.group(2)
out.append('enum class EffectType(val title: String, val summary: String, val defaultAmount: Double) {')
out.append(',\n'.join(f'    {c}({q(t[c])}, {q(s[c])}, {num('x', amount.get(c, "0.5"))})' for c in cases(blk)) + ';\n}\n')

# TransitionType
blk = enum_block('TransitionType'); t = mapping(blk, 'title')
out.append('enum class TransitionType(val title: String) {')
out.append(',\n'.join(f'    {c}({q(t[c])})' for c in cases(blk)) + ';\n}\n')

# GeneratorKind
blk = enum_block('GeneratorKind'); t = mapping(blk, 'title'); s = mapping(blk, 'summary')
out.append('enum class GeneratorKind(val title: String, val summary: String) {')
out.append(',\n'.join(f'    {c}({q(t[c])}, {q(s[c])})' for c in cases(blk)) + ';\n}\n')

# Look presets
names = re.search(r'presetNames = \[(.*?)\]', src, re.S).group(1)
names = re.findall(r'"([^"]+)"', names)
pm = re.search(r'public static func preset\(_ name: String\) -> Look\? \{(.*?)\n    \}', src, re.S).group(1)
lines = []
for line in pm.split('\n'):
    m = re.match(r'\s+case (.*?): (.*)$', line)
    if not m or 'default' in line: continue
    keys = re.findall(r'"([^"]+)"', m.group(1))
    body = m.group(2)
    sets = re.findall(r'l\.(\w+) = ("[^"]*"|-?[0-9.]+|true|false)', body)
    args = ', '.join(f'{k} = {num(k, v)}' for k, v in sets)
    lines.append((keys, args))
out.append('object LookPresets {')
out.append('    val names = listOf(' + ', '.join(q(n) for n in names) + ')')
out.append('    fun preset(name: String): Look? = when (name.lowercase()) {')
for keys, args in lines:
    out.append(f'        {", ".join(q(k) for k in keys)} -> Look({args})')
out.append('        else -> null\n    }\n}\n')

# TitlePreset
blk = enum_block('TitlePreset'); rc = raw_cases(blk)
texts = mapping(blk, 'text')
style_m = re.search(r'public var style: TextStyle \{(.*?)\n        \}\n        return s', blk, re.S).group(1)
styles = {}
for line in style_m.split('\n'):
    m = re.match(r'\s+case \.(\w+): (.*)$', line)
    if not m: continue
    sets = re.findall(r's\.(\w+) = ("[^"]*"|\.\w+|-?[0-9.]+|true|false)', m.group(2))
    args = []
    for k, v in sets:
        if v.startswith('.'): v = 'TextAnimation.' + v[1:]
        args.append(f'{k} = {num(k, v)}')
    styles[m.group(1)] = ', '.join(args)
out.append('enum class TitlePreset(val label: String, val sampleText: String) {')
out.append(',\n'.join(f'    {c}({q(lab)}, {q(texts[c])})' for c, lab in rc) + ';\n')
out.append('    val style: TextStyle get() = when (this) {')
for c, _ in rc: out.append(f'        {c} -> TextStyle({styles.get(c, "")})')
out.append('    }\n')
out.append('    companion object {\n        fun named(name: String): TitlePreset? {\n            fun key(s: String) = s.lowercase().filter { it.isLetter() }\n            return entries.firstOrNull { key(it.label) == key(name) || key(it.name) == key(name) }\n        }\n    }\n}\n')
open('android/app/src/main/kotlin/app/lumacut/core/Catalog.kt', 'w').write('\n'.join(out))
print('ok', len(cases(enum_block('EffectType'))), 'effects', len(cases(enum_block('TransitionType'))), 'transitions', len(cases(enum_block('GeneratorKind'))), 'overlays', len(rc), 'titles', len(lines), 'looks')
