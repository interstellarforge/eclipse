#!/usr/bin/env python3
"""Generates android content (templates, treatments, skills) from the Swift sources so both apps stay in step."""
import re, os, json
OUT = 'android/app/src/main/kotlin/app/lumacut/core'
ASSETS = 'android/app/src/main/assets/skills'

def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'
def num(v): return v + '.0' if re.fullmatch(r'-?[0-9]+', v) else v

# ---------- Templates ----------
t = open('Sources/MovieCore/Templates.swift').read()
body = t[t.index('public static let all: [EditTemplate] = ['):t.index('public static var categories')]
entries = []
i = 0
while True:
    i = body.find('        t("', i)
    if i < 0: break
    depth = 0; j = body.index('t(', i) + 1; k = j
    instr = False
    while True:
        c = body[k]
        if c == '"' and body[k-1] != '\\': instr = not instr
        elif not instr:
            if c == '(': depth += 1
            elif c == ')':
                depth -= 1
                if depth == 0: break
        k += 1
    entries.append(body[body.index('t(', i) + 2:k]); i = k
lines = []
for e in entries:
    name, cat, summary = re.match(r'"([^"]*)", "([^"]*)", "((?:[^"\\]|\\.)*)"', e).groups()
    lm = re.search(r'look: look\("([^"]+)"\)(?: \{ ([^}]*) \})?', e)
    preset = lm.group(1); tweaks = re.findall(r'\$0\.(\w+) = ("[^"]*"|-?[0-9.]+)', lm.group(2) or '')
    effects = re.findall(r'Effect\(\.(\w+)(?:, amount: ([0-9.]+))?\)', e)
    tr = re.search(r'transition: \.(\w+)', e); ms = re.search(r', ms: ([0-9_]+)', e)
    title = re.search(r'title: \.(\w+)', e); ov = re.search(r'overlay: \.(\w+)', e); ova = re.search(r'overlayAmount: ([0-9.]+)', e)
    music = re.search(r'music: "([^"]*)"', e); pace = re.search(r'pace: "((?:[^"\\]|\\.)*)"', e)
    tw = ', '.join(f'{k} = {num(v)}' for k, v in tweaks)
    look = f'(LookPresets.preset({q(preset)}) ?: Look())' + (f'.copy({tw})' if tw else '')
    fx = ', '.join(f'Effect(type = EffectType.{n}' + (f', amount = {a}' if a else '') + ')' for n, a in effects)
    lines.append(f'''        EditTemplate({q(name.lower().replace(" ", "").replace("-", ""))}, {q(name)}, {q(cat)}, {q(summary)}, {look},
            effects = listOf({fx}), transition = {("TransitionType." + tr.group(1)) if tr else "null"}, transitionMs = {ms.group(1).replace("_", "") if ms else "500"},
            titleStyle = {("TitlePreset." + title.group(1)) if title else "null"}, overlay = {("GeneratorKind." + ov.group(1)) if ov else "null"}, overlayAmount = {ova.group(1) if ova else "0.4"},
            music = {q(music.group(1)) if music else "null"}, pace = {q(pace.group(1))})''')
open(f'{OUT}/TemplateData.kt', 'w').write('''// GENERATED by scripts/gen-android-content.py from Templates.swift. Do not edit by hand.
package app.lumacut.core

object TemplateData {
    val all: List<EditTemplate> = listOf(
''' + ',\n'.join(lines) + '\n    )\n}\n')
print(len(lines), 'templates')

# ---------- Treatments ----------
tr = open('Sources/MovieCore/Treatments.swift').read()
tb = tr[tr.index('public static let all: [Treatment] = ['):tr.index('/// Random constraints')]
items = []
for m in re.finditer(r'Treatment\(name: "([^"]*)", moods: \[([^\]]*)\],\s*idea: "((?:[^"\\]|\\.)*)",\s*structure: "((?:[^"\\]|\\.)*)",\s*transitions: \[([^\]]*)\], look: "([^"]*)", effects: \[((?:\([^)]*\)(?:, )?)*)\], overlay: (nil|\.\w+), title: \.(\w+),\s*speed: "((?:[^"\\]|\\.)*)", restraint: "((?:[^"\\]|\\.)*)"\)', tb):
    name, moods, idea, structure, trans, look, effects, overlay, title, speed, restraint = m.groups()
    moods = re.findall(r'"([^"]*)"', moods)
    trans = re.findall(r'\.(\w+)', trans)
    fx = re.findall(r'\(\.(\w+), ([0-9.]+)\)', effects)
    items.append(f'''        Treatment({q(name)}, listOf({", ".join(q(x) for x in moods)}), {q(idea.replace('\\"','"'))}, {q(structure.replace('\\"','"'))},
            listOf({", ".join("TransitionType." + x for x in trans)}), {q(look)}, listOf({", ".join(f"EffectType.{a} to {b}" for a, b in fx)}),
            {"null" if overlay == "nil" else "GeneratorKind." + overlay[1:]}, TitlePreset.{title}, {q(speed.replace('\\"','"'))}, {q(restraint.replace('\\"','"'))})''')
cons = re.findall(r'^\s+"((?:[^"\\]|\\.)*)",$', tr[tr.index('public static let constraints'):tr.index('public static func drawConstraints')], re.M)
open(f'{OUT}/TreatmentData.kt', 'w').write('''// GENERATED by scripts/gen-android-content.py from Treatments.swift. Do not edit by hand.
package app.lumacut.core

object TreatmentData {
    val all: List<Treatment> = listOf(
''' + ',\n'.join(items) + '''
    )

    val constraints: List<String> = listOf(
''' + ',\n'.join('        ' + q(c.replace('\\"', '"')) for c in cons) + '\n    )\n}\n')
print(len(items), 'treatments', len(cons), 'constraints')

# ---------- Skills ----------
sk = open('Sources/MovieCore/SkillContent.swift').read()
os.makedirs(ASSETS, exist_ok=True)
for f in os.listdir(ASSETS): os.remove(f'{ASSETS}/{f}')
index = []
for m in re.finditer(r'\("([a-z-]+)",\s*"((?:[^"\\]|\\.)*)",\s*#"""\n(.*?)\n\s*"""#\)', sk, re.S):
    name, summary, text = m.groups()
    # strip the common leading indent of the raw string
    lines_ = text.split('\n'); indent = min(len(l) - len(l.lstrip()) for l in lines_ if l.strip())
    text = '\n'.join(l[indent:] for l in lines_)
    open(f'{ASSETS}/{name}.md', 'w').write(text + '\n')
    index.append({'name': name, 'summary': summary.replace('\\"', '"')})
json.dump(index, open(f'{ASSETS}/index.json', 'w'), indent=1)
print(len(index), 'skills')

# ---------- Prompt ideas ----------
pl = open('Sources/MovieMaker/PromptLibrary.swift').read()
ideas = re.findall(r'\("([^"]+)", PromptIdea\(emoji: "([^"]*)", title: "((?:[^"\\]|\\.)*)", subtitle: "((?:[^"\\]|\\.)*)",\s*prompt: "((?:[^"\\]|\\.)*)"\)\)', pl)
cats = re.findall(r'"([^"]+)"', re.search(r'static let categories = \[(.*?)\]', pl).group(1))
def un(s): return s.replace('\\"', '"').replace('\\n', '\n')
open(f'{OUT}/PromptData.kt', 'w').write('''// GENERATED by scripts/gen-android-content.py from PromptLibrary.swift. Do not edit by hand.
package app.lumacut.core

data class PromptIdea(val category: String, val emoji: String, val title: String, val subtitle: String, val prompt: String)

object PromptData {
    val categories = listOf(''' + ', '.join(q(c) for c in cats) + ''')
    val all = listOf(
''' + ',\n'.join(f'        PromptIdea({q(c)}, {q(e)}, {q(un(t))}, {q(un(s))}, {q(un(p))})' for c, e, t, s, p in ideas) + '\n    )\n}\n')
print(len(ideas), 'prompt ideas')

# ---------- Music songs ----------
ms = open('Sources/MovieCore/MusicLibrary.swift').read()
body = ms[ms.index('private static let songs: [Song] = ['):ms.index('public static let tracks')]
songs = []
i = 0
while True:
    i = body.find('Song(name:', i)
    if i < 0: break
    depth = 0; k = body.index('(', i); j = k
    instr = False
    while True:
        c = body[j]
        if c == '"': instr = not instr
        elif not instr:
            if c in '([': depth += 1
            elif c in ')]':
                depth -= 1
                if depth == 0: break
        j += 1
    inner = body[k + 1:j]; i = j
    parts = []; cur = ''; d = 0; st = False
    for c in inner:
        if c == '"': st = not st
        if not st:
            if c in '[(': d += 1
            if c in '])': d -= 1
            if c == ',' and d == 0: parts.append(cur.strip()); cur = ''; continue
        cur += c
    parts.append(cur.strip())
    args = []
    for p in parts:
        key, val = p.split(':', 1); key = key.strip(); val = val.strip()
        if val.startswith('['): val = 'listOf(' + val[1:-1] + ')'
        elif re.match(r'^(eighths|sixteenths|fourFloor)\b', val):
            val = re.sub(r'\beighths\b', 'EIGHTHS', val); val = re.sub(r'\bsixteenths\b', 'SIXTEENTHS', val); val = re.sub(r'\bfourFloor\b', 'FOUR_FLOOR', val); val = val.replace('$0', 'it')
        elif val.startswith('.'): val = ('Voice.' if key == 'voice' else 'Bass.') + val[1:]
        args.append(f'{key} = {val}')
    songs.append('        Song(' + ', '.join(args) + ')')
open(f'{OUT}/SongData.kt', 'w').write('''// GENERATED by scripts/gen-android-content.py from MusicLibrary.swift. Do not edit by hand.
package app.lumacut.core

object SongData {
    val EIGHTHS = listOf(0, 2, 4, 6, 8, 10, 12, 14)
    val SIXTEENTHS = (0 until 16).toList()
    val FOUR_FLOOR = listOf(0, 4, 8, 12)

    val songs: List<Song> = listOf(
''' + ',\n'.join(songs) + '\n    )\n}\n')
print(len(songs), 'songs')
